// Validates questions/*.json (one file per subject) and generates js/questions.js.
const fs = require('node:fs');
const path = require('node:path');

const INVALID_JSON = Symbol('invalid json');

const ID_FORMAT = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const FIELDS = [
  'id', 'lang', 'topics', 'difficulty', 'place', 'minAge', 'maxAge',
  'prompt', 'options', 'correct', 'explanation', 'references'
];
const OUTPUT_FIELDS = [
  'id', 'lang', 'subject', 'topics', 'difficulty', 'place', 'minAge', 'maxAge',
  'prompt', 'options', 'correct', 'explanation', 'references'
];
const LANGUAGES = ['es', 'ca', 'en'];
const FIXED_LANGUAGE = { english: 'en', catalan: 'ca', language: 'es' };
const PLACE_SUBJECTS = ['geography', 'history', 'sports', 'culture'];
const MAX_PROMPT = 120;
const MAX_OPTION = 40;
const MAX_EXPLANATION = 160;
const HEADER = '// Generated by scripts/build-questions.js from questions/*.json. Do not edit by hand.';

const isObject = (value) => typeof value === 'object' && value !== null && !Array.isArray(value);
const isText = (value) => typeof value === 'string';

function validateQuestion(q, subject, topicIds, stopIds, report) {
  for (const field of FIELDS) {
    if (!(field in q)) report(`missing field "${field}"`);
  }
  for (const field of Object.keys(q)) {
    if (!FIELDS.includes(field)) report(`unknown field "${field}"`);
  }
  const has = (field) => field in q;

  if (has('lang')) {
    const expected = FIXED_LANGUAGE[subject];
    const fits = expected ? q.lang === expected : q.lang === 'es' || q.lang === 'ca';
    if (!LANGUAGES.includes(q.lang) || !fits) {
      report(`language "${q.lang}" does not match subject "${subject}"`);
    }
  }
  if (has('topics')) {
    const topics = q.topics;
    if (!Array.isArray(topics) || topics.length < 1 || topics.length > 3 || new Set(topics).size !== topics.length) {
      report('needs 1 to 3 different topics');
    } else {
      for (const t of topics) {
        if (!topicIds.has(t)) report(`unknown topic "${t}"`);
      }
    }
  }
  if (has('difficulty') && ![1, 2, 3].includes(q.difficulty)) report('difficulty must be 1, 2 or 3');
  if (has('place')) {
    if (q.place !== 'general' && !stopIds.includes(q.place)) {
      report(`unknown place "${q.place}"`);
    } else if (q.place !== 'general' && !PLACE_SUBJECTS.includes(subject)) {
      report('a question about a place must be geography, history, sports or culture');
    }
  }
  if ((has('minAge') || has('maxAge')) && (q.minAge !== 10 || q.maxAge !== 12)) {
    if ((has('minAge') && q.minAge !== 10) || (has('maxAge') && q.maxAge !== 12)) report('ages must be 10 to 12');
  }
  if (has('options')) {
    const options = q.options;
    const good = Array.isArray(options) && options.length === 4 &&
      options.every((o) => isText(o) && o.trim() !== '') && new Set(options).size === 4;
    if (!good) {
      report('needs 4 different non-blank options');
    } else if (options.some((o) => o.length > MAX_OPTION)) {
      report(`option longer than ${MAX_OPTION} characters`);
    }
  }
  if (has('correct') && !(Number.isInteger(q.correct) && q.correct >= 0 && q.correct <= 3)) {
    report('correct must be 0 to 3');
  }
  if (has('prompt') && isText(q.prompt) && q.prompt.length > MAX_PROMPT) {
    report(`prompt longer than ${MAX_PROMPT} characters`);
  }
  if (has('explanation') && isText(q.explanation) && q.explanation.length > MAX_EXPLANATION) {
    report(`explanation longer than ${MAX_EXPLANATION} characters`);
  }
  if (has('references')) {
    const refs = q.references;
    if (!Array.isArray(refs) || !refs.some((r) => isText(r) && r.startsWith('https://'))) {
      report('needs at least one https reference');
    }
  }
}

function validateBank(files, context) {
  const problems = [];
  const seenTopics = new Set();
  const seenQuestions = new Set();
  const present = new Set();

  for (const { file, data } of files) {
    const subject = file.replace(/\.json$/, '');
    if (data === INVALID_JSON) {
      problems.push(`${file}: -: invalid JSON`);
      present.add(subject);
      continue;
    }
    if (!isObject(data) || !Array.isArray(data.topics) || !Array.isArray(data.questions)) {
      problems.push(`${file}: -: must be an object with "topics" and "questions" arrays`);
      present.add(subject);
      continue;
    }
    if (!file.endsWith('.json') || !context.subjects.includes(subject)) {
      problems.push(`${file}: -: not a subject`);
      continue;
    }
    present.add(subject);

    const topicIds = new Set();
    for (const topic of data.topics) {
      const id = isObject(topic) ? topic.id : undefined;
      if (typeof id !== 'string' || !ID_FORMAT.test(id)) {
        problems.push(`${file}: -: invalid topic id "${id}"`);
      } else if (seenTopics.has(id)) {
        problems.push(`${file}: -: duplicate topic id "${id}"`);
      } else {
        seenTopics.add(id);
        topicIds.add(id);
      }
    }

    for (const q of data.questions) {
      const usable = isObject(q) && typeof q.id === 'string' && q.id !== '';
      const id = usable ? q.id : '?';
      const report = (text) => problems.push(`${file}: ${id}: ${text}`);
      if (!isObject(q)) {
        report('invalid id');
        continue;
      }
      if (!('id' in q) || typeof q.id !== 'string' || !ID_FORMAT.test(q.id)) {
        report('invalid id');
      } else if (seenQuestions.has(q.id)) {
        report('duplicate id');
      } else {
        seenQuestions.add(q.id);
      }
      validateQuestion(q, subject, topicIds, context.stopIds, report);
    }
  }

  for (const subject of context.subjects) {
    if (!present.has(subject)) problems.push(`${subject}.json: -: missing file`);
  }
  return problems;
}

function renderQuestionsJs(files, subjects) {
  const topics = [];
  const questions = [];
  for (const subject of subjects) {
    const entry = files.find((f) => f.file === `${subject}.json`);
    if (!entry) continue;
    for (const t of entry.data.topics) topics.push({ id: t.id, subject, name: t.name });
    for (const q of entry.data.questions) {
      const out = {};
      for (const field of OUTPUT_FIELDS) out[field] = field === 'subject' ? subject : q[field];
      questions.push(out);
    }
  }
  const indent = (value) => JSON.stringify(value, null, 2).replace(/\n/g, '\n  ');
  return [
    HEADER,
    '(function () {',
    '  const APN = (globalThis.APN = globalThis.APN || {});',
    `  APN.TOPICS = ${indent(topics)};`,
    `  APN.QUESTIONS = ${indent(questions)};`,
    '})();',
    ''
  ].join('\n');
}

function buildQuestions(dir, context) {
  const names = fs.readdirSync(dir).filter((n) => n.endsWith('.json')).sort();
  const files = names.map((file) => {
    let data;
    try {
      data = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    } catch {
      data = INVALID_JSON;
    }
    return { file, data };
  });
  const problems = validateBank(files, context);
  return { problems, output: problems.length ? null : renderQuestionsJs(files, context.subjects) };
}

function main() {
  const root = path.join(__dirname, '..');
  require(path.join(root, 'js', 'data-level-1.js'));
  const level = globalThis.APN.LEVELS[0];
  const context = { subjects: globalThis.APN.SUBJECTS, stopIds: level.stops.map((s) => s.id) };
  const dir = path.join(root, 'questions');
  const { problems, output } = fs.existsSync(dir)
    ? buildQuestions(dir, context)
    : { problems: context.subjects.map((s) => `${s}.json: -: missing file`), output: null };
  if (output === null) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  fs.writeFileSync(path.join(root, 'js', 'questions.js'), output);
  console.log('Wrote js/questions.js');
}

if (require.main === module) main();

module.exports = { validateBank, renderQuestionsJs, buildQuestions, INVALID_JSON };
